  /**
   * Search / filter catalog by options
   */
  findOpportunities(filters = {}) {
    const {
      marketplace = 'any',
      category = 'any',
      budget = 500,
      searchQuery = '',
      strategy = 'any'
    } = filters;

    let list = this.products.map(p => {
      const comp = CompetitionDetector.evaluate({
        competingListings: p.competingListings,
        strongCompetitors: p.strongCompetitors,
        medianReviews: p.medianReviews,
        listingQualityDeficit: p.listingQualityDeficit,
        establishedSellerShare: p.establishedSellerShare,
        searchDensity: p.searchDensity,
        priceClustering: p.priceClustering,
        productSimilarity: p.productSimilarity
      });

      // Override if item has exact calibrated target
      if (p.targetCompetitionScore) {
        comp.score = p.targetCompetitionScore;
        const lvl = CompetitionDetector.getLevel(p.targetCompetitionScore);
        comp.level = lvl.label;
        comp.color = lvl.color;
        comp.badgeClass = lvl.badgeClass;
      }

      const dem = DemandDetector.evaluate({
        monthlySalesMin: p.monthlySalesMin,
        monthlySalesMax: p.monthlySalesMax,
        avgPrice: p.price,
        reviewVelocityMonthly: p.reviewVelocityMonthly,
        inCartSignalCount: p.inCartSignalCount,
        favoritesSignalCount: p.favoritesSignalCount,
        searchVolumeIndex: p.searchVolumeIndex,
        listingGrowthRate: p.listingGrowthRate,
        trendMomentum: p.trendMomentum
      });

      if (p.targetDemandScore) {
        dem.score = p.targetDemandScore;
        dem.level = dem.score >= 80 ? 'High' : 'Medium';
      }

      const prof = ProfitCalculator.calculate({
        sellingPrice: p.price,
        productCost: p.cost,
        shippingCost: p.shippingCost,
        marketplace: p.preferredMarketplace || 'etsy'
      });

      const trnd = TrendAnalyzer.analyze({
        status: (p.trend || 'rising').toLowerCase(),
        change30d: p.trendChange30d || 24,
        change90d: p.trendChange90d || 68,
        historyPoints: p.trendPoints || [40, 50, 60, 70, 80, 90]
      });

      if (p.targetTrendScore) {
        trnd.score = p.targetTrendScore;
      }

      const oppScore = p.targetOpportunityScore || Math.round(
        (dem.score * 0.35) +
        ((100 - comp.score) * 0.35) +
        (Math.min(100, prof.profitMargin * 1.3) * 0.20) +
        (trnd.score * 0.10)
      );

      const profitScore = p.targetProfitScore || Math.min(99, Math.round(prof.profitMargin * 1.3));

      return {
        ...p,
        competitionScore: comp.score,
        competitionLevel: comp.level,
        competitionColor: comp.color,
        competitionData: comp,
        demandScore: dem.score,
        demandLevel: dem.level,
        demandColor: dem.color,
        demandData: dem,
        profitScore: profitScore,
        profitMargin: prof.profitMargin,
        profitMarginFormatted: prof.profitMarginFormatted,
        profitData: prof,
        trendScore: trnd.score,
        trendLabel: trnd.symbol + ' ' + trnd.status,
        trendData: trnd,
        opportunityScore: oppScore
      };
    });

    // Apply filters
    if (category && category.toLowerCase() !== 'any' && category.toLowerCase() !== 'all') {
      list = list.filter(p => p.category.toLowerCase().includes(category.toLowerCase()));
    }

    if (marketplace && marketplace.toLowerCase() !== 'any' && marketplace.toLowerCase() !== 'all') {
      list = list.filter(p => (p.preferredMarketplace || '').toLowerCase().includes(marketplace.toLowerCase()));
    }

    if (budget && Number(budget) > 0) {
      list = list.filter(p => (p.budgetTier || 100) <= Number(budget));
    }

    if (searchQuery && searchQuery.trim() !== '') {
      const q = searchQuery.toLowerCase().trim();
      const filtered = list.filter(p =>
        p.name.toLowerCase().includes(q) ||
        p.category.toLowerCase().includes(q) ||
        (p.subCategory || '').toLowerCase().includes(q)
      );
      if (filtered.length > 0) {
        list = filtered;
      } else {
        const synth = this.synthesizeProduct(searchQuery, category, marketplace);
        list = [synth];
      }
    }

    // Sort strictly by opportunityScore descending (highest opportunity first)
    list.sort((a, b) => b.opportunityScore - a.opportunityScore);

    return list;
  },

