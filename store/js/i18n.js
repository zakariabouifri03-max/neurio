export function makeT(lang) {
  const dict = I18N[lang] || I18N.en;
  return (key, vars = {}) => {
    let str = dict[key] ?? I18N.en[key] ?? key;
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
    return str;
  };
}
