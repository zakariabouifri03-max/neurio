// Builds freefire/BOOYAH-FIRE.html — the whole game as ONE file you can open by
// double-clicking. That means no ES modules (a file:// page cannot use import
// maps), no service worker, no fetch, no relative URLs: the three.js bundle, the
// stylesheet and the favicon are all inlined into the document.
//
//   node tools/build-standalone.mjs [--out BOOYAH-FIRE.html]
//
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { inlineGameHtml, assertSelfContained } from './build-apk.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');

export const BANNER = `<!--
  BOOYAH FIRE — single-file build.
  Double-click this file: no server, no install, no network. Works offline from a
  USB stick. Everything (game code, three.js, styles, icon) is inlined below.
  Generated by tools/build-standalone.mjs — edit src/ and rebuild, not this file.
-->`;

export function buildStandalone({ out = path.join(root, 'BOOYAH-FIRE.html'), quiet = false } = {}) {
  const html = inlineGameHtml({ banner: BANNER });
  assertSelfContained(html);
  fs.writeFileSync(out, html, 'utf8');
  const scripts = [...html.matchAll(/<script/g)].length;
  const info = {
    out, bytes: Buffer.byteLength(html), scripts,
    modules: /<script[^>]+type="module"/.test(html),
    importMap: html.includes('importmap'),
    serviceWorker: html.includes("serviceWorker' in navigator"),
  };
  if (!quiet) {
    console.log(`BOOYAH FIRE → ${out}`);
    console.log(`  ${(info.bytes / 1048576).toFixed(2)} MB · ${scripts} inline script(s) · no module loading, no import map, no external file`);
    console.log('  open it directly in a browser (file://) — nothing else needed');
  }
  return info;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const i = process.argv.indexOf('--out');
  buildStandalone({ out: i > 0 ? path.resolve(process.argv[i + 1]) : undefined });
}
