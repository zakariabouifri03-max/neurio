// Converts the vendored ESM build vendor/three.module.js (r170)
// into a classic script scam/vendor/three.global.js that exposes `window.THREE`.
// This lets the scam-with-friends clone run straight from file:// with no server,
// no import-map and no bundler (100% offline, zero dependencies).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const srcPath = root + 'vendor/three.module.js';
const outPath = root + 'scam/vendor/three.global.js';

const src = readFileSync(srcPath, 'utf8');
const m = src.match(/\nexport\s*\{([\s\S]*?)\};?\s*$/);
if (!m) {
  console.error('Could not find the trailing export block in three.module.js');
  process.exit(1);
}
const names = m[1]
  .split(',')
  .map((s) => s.trim())
  .filter(Boolean)
  .map((s) => {
    const as = s.split(/\s+as\s+/);
    return (as[1] || as[0]).trim();
  });

const body = src.slice(0, m.index);
const out =
  '/*! three.js r170 — MIT License — (c) 2010-2024 Three.js Authors\n' +
  ' *  Auto-generated by tools/make-three-global.mjs from vendor/three.module.js.\n' +
  ' *  Do not edit by hand. Exposes window.THREE (classic script, works from file://).\n' +
  ' */\n(function () {\n"use strict";\n' +
  body +
  '\nwindow.THREE = {' + names.join(', ') + '};\n})();\n';

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
console.log(
  'scam/vendor/three.global.js written:',
  (out.length / 1024 / 1024).toFixed(2),
  'MB,',
  names.length,
  'exports'
);
